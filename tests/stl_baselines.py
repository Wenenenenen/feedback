"""
STL reference snapshots generated by the *original* library code (before
color support was added). Tests in test_stl_compat.py regenerate the same
models with the current code and compare binary hashes, guaranteeing the
geometry path is byte-for-byte unchanged.
"""

# sha256 of the binary STL written for each model below
BASELINE_HASHES = {
    'csg.stl': '7b58a9313c36b060b7e141e8bd1971f2358faa84956298f5a92675cf9f457b90',
    'extrude.stl': '7abbb6280608c5acd2d93fdfe6e05af16330f46336c4ecced5e657563419933f',
    'revolve.stl': '670be9df88bfea7e51f4d199a5ac52481a21e0e01b432bdc829de8d950485aa8',
    'ops.stl': '0d171e84abeb6535a1801d5ef96386f182e735b4f124b663fa40d758a93655d2',
}

SAMPLES = 2 ** 18


def build_model(name):
    """Each model is built with explicit, deterministic parameters."""
    from sdf import sphere, box, cylinder, circle, rectangle, X, Y, Z

    if name == 'csg.stl':
        f = sphere(1) & box(1.5)
        c = cylinder(0.5)
        f -= c.orient(X) | c.orient(Y) | c.orient(Z)
        return f, {}

    if name == 'extrude.stl':
        g = circle(0.5) | rectangle((0.8, 0.4)).translate((0.6, 0))
        return g.extrude(0.5), {}

    if name == 'revolve.stl':
        g = circle(0.5) | rectangle((0.8, 0.4)).translate((0.6, 0))
        return g.revolve(0.2), {}

    if name == 'ops.stl':
        f = sphere(0.6).translate((-0.8, 0, 0))
        f |= box(1).k(0.2).translate((0.8, 0, 0))
        f = f.twist(0.7)
        f |= cylinder(0.3).translate((0, 1.2, 0))
        f = f.shell(0.08)
        return f, {
            'bounds': ((-2.5, -2.5, -2.5), (2.5, 2.5, 2.5)),
        }

    raise KeyError(name)
